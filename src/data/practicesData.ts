interface PracticeInput {
  id: string;
  dayNumber: number;
  titulo: string;
  subtitle?: string;
  quandoUsar: string;
  descricao: string;
  duracao: string;
  durationMinutes: number;
  perguntaPosPratica: string;
  categoria: PracticeCategory;
  isAvailable: boolean;
  instrucoes: string[];
  arquivoAudio?: string;
  arquivoVideo?: string;
  focusArea?: string;
}

function buildPractice(input: PracticeInput): Practice {
  const audioFile = input.arquivoAudio || '/audio/pratica-dia-1.wav';
  return {
    id: input.id,
    dayNumber: input.dayNumber,

    // Título
    titulo: input.titulo,
    title: input.titulo,
    subtitle: input.subtitle,

    // Descrição
    descricao: input.descricao,
    description: input.descricao,
    practiceDescription: input.descricao,

    // Duração
    duracao: input.duracao,
    durationDisplay: input.duracao,
    durationMinutes: input.durationMinutes,

    // Categoria
    categoria: input.categoria,
    category: input.categoria,

    // Quando usar
    quandoUsar: input.quandoUsar,
    whenToUse: input.quandoUsar,

    // Instruções
    instrucoes: input.instrucoes,
    instructions: input.instrucoes,
    guidedPhrases: input.instrucoes,

    // Arquivos de Mídia
    arquivoAudio: audioFile,
    audioUrl: audioFile,
    arquivoVideo: input.arquivoVideo,
    videoUrl: input.arquivoVideo,

    // Pergunta reflexiva pós-prática
    perguntaPosPratica: input.perguntaPosPratica,
    reflectionQuestion: input.perguntaPosPratica,

    // Metadados
    focusArea: input.focusArea,
    isAvailable: input.isAvailable,
  };
}

